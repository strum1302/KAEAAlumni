-- ── 0) 매칭 확인: 아래 24명 중 members 테이블에 이름이 없거나(0건), 동명이인으로
--      여러 명 매칭되는(2건 이상) 이름을 확인합니다. 결과가 없으면 전원 정상 매칭. ──
WITH candidates(name) AS (
  VALUES
  ('고경남'),('오승화'),('문봉주'),('송원준'),('김은영'),('김기훈'),
  ('LM부티스쿨'),('윤근'),('오세진'),('Michelle Kim'),
  ('한홍기'),('이창환'),('이호영'),('윤근흠'),('변문수'),('도태환'),
  ('서원경'),('황광연'),('최창익'),('신승경'),('오국정'),('최충길'),
  ('박기선'),('민광홍')
)
SELECT c.name, count(m.id) AS match_count
FROM candidates c
LEFT JOIN members m ON m.name = c.name
GROUP BY c.name
HAVING count(m.id) != 1
ORDER BY c.name;

-- ── 1) 2024 골프대회 (9/1) — 10건, $2,340 ────────────────────────────────
INSERT INTO payments (id, member_id, payment_type, target_year, amount, payment_method, payment_status, payment_date, purpose_detail, receipt_issued, created_at)
